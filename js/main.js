// Shopping cart: persistent in localStorage
var autoCart = JSON.parse(localStorage.getItem('spsmCart') || '[]');
var cart = Array.isArray(autoCart) ? autoCart : [];

function formatIDR(value) {
    return 'IDR ' + Number(value || 0).toLocaleString('id-ID');
}
function numericPrice(text) {
    var m = String(text || '').replace(/,/g, '').match(/\d+/g);
    return m ? Number(m[m.length - 1]) : 0;
}
function saveCart() {
    localStorage.setItem('spsmCart', JSON.stringify(cart));
    renderCart();
}
function cartCountTotal() {
    return cart.reduce(function(sum, item) { return sum + item.qty; }, 0);
}
function renderCart() {
    var countEl = document.getElementById('cartCount');
    var itemsEl = document.getElementById('cartItems');
    var totalEl = document.getElementById('cartTotal');
    if (!countEl || !itemsEl || !totalEl) return;
    countEl.textContent = cartCountTotal();
    if (!cart.length) {
        itemsEl.innerHTML = '<div class="cart-empty"><i class="fas fa-shopping-basket"></i><h4>Your cart is empty</h4><p>Add your favorite dishes from the menu.</p></div>';
        totalEl.textContent = 'IDR 0';
        return;
    }
    var total = 0;
    itemsEl.innerHTML = cart.map(function(item, index) {
        var line = item.price * item.qty;
        total += line;
        return '<div class="cart-line">' +
          '<img src="' + item.img + '" alt="' + item.title.replace(/"/g, '&quot;') + '">' +
          '<div><h5>' + item.title + '</h5><small>' + formatIDR(item.price) + '</small>' +
          '<div class="cart-controls"><button data-cart-action="minus" data-index="' + index + '">−</button><strong>' + item.qty + '</strong><button data-cart-action="plus" data-index="' + index + '">+</button></div></div>' +
          '<button class="cart-remove" data-cart-action="remove" data-index="' + index + '" aria-label="Remove item"><i class="fas fa-trash"></i></button>' +
          '</div>';
    }).join('');
    totalEl.textContent = formatIDR(total);
}
function openCart() {
    document.getElementById('cartDrawer').classList.add('open');
    document.getElementById('cartOverlay').classList.add('open');
    document.body.style.overflow = 'hidden';
    renderCart();
}
function closeCart() {
    document.getElementById('cartDrawer').classList.remove('open');
    document.getElementById('cartOverlay').classList.remove('open');
    document.body.style.overflow = '';
}
function addToCartFromModal() {
    var title = document.getElementById('mpTitle').textContent;
    var img = document.getElementById('mpImg').getAttribute('src');
    var price = numericPrice(document.getElementById('mpPrice').textContent);
    var existing = cart.find(function(item) { return item.title === title; });
    if (existing) existing.qty += mpQty;
    else cart.push({title:title, img:img, price:price, qty:mpQty});
    saveCart();
    this.innerHTML = '<i class="fas fa-check"></i> Added to Cart!';
    this.style.background = 'linear-gradient(135deg,var(--green),#1a4a35)';
    var self = this;
    setTimeout(function() {
        closeMenuPop();
        self.innerHTML = '<i class="fas fa-shopping-cart"></i> Add to Cart';
        self.style.background = '';
    }, 700);
}
